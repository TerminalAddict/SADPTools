package streaming

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"math/bits"
	"strings"

	"github.com/bluenviron/mediacommon/v2/pkg/codecs/h264"
	"github.com/bluenviron/mediacommon/v2/pkg/codecs/h265"
	"github.com/bluenviron/mediacommon/v2/pkg/formats/fmp4"
	"github.com/bluenviron/mediacommon/v2/pkg/formats/fmp4/seekablebuffer"
	"github.com/bluenviron/mediacommon/v2/pkg/formats/mp4/codecs"
)

type videoMux struct {
	hevc             bool
	vps, sps, pps    []byte
	started          bool
	h264DTS          h264.DTSExtractor
	h265DTS          h265.DTSExtractor
	origin, previous int64
	pending          *fmp4.Sample
	sequence         uint32
	sink             Sink
}

func (m *videoMux) accessUnit(au [][]byte, pts int64) error {
	if len(au) > 2048 {
		return ErrMedia
	}
	size := 0
	hasVideo, key := false, false
	for _, n := range au {
		size += len(n)
		if len(n) == 0 || size > MaxFrame {
			return ErrMedia
		}
		var destination *[]byte
		if m.hevc {
			if len(n) < 2 {
				return ErrMedia
			}
			t := (n[0] >> 1) & 63
			switch t {
			case 32:
				destination = &m.vps
			case 33:
				destination = &m.sps
			case 34:
				destination = &m.pps
			}
			hasVideo = hasVideo || t <= 31
			key = key || (t >= 16 && t <= 21)
		} else {
			t := n[0] & 31
			switch t {
			case 7:
				destination = &m.sps
			case 8:
				destination = &m.pps
			}
			hasVideo = hasVideo || t == 1 || t == 5
			key = key || t == 5
		}
		if destination != nil {
			if len(n) > 4096 {
				return ErrMedia
			}
			if m.started && !bytes.Equal(*destination, n) {
				return fmt.Errorf("camera changed codec parameters during playback; stop and reopen the preview")
			}
			*destination = bytes.Clone(n)
		}
	}
	if !hasVideo {
		return nil
	}
	if !m.started {
		if !key || len(m.sps) == 0 || len(m.pps) == 0 || (m.hevc && len(m.vps) == 0) {
			return nil
		}
		if err := m.init(); err != nil {
			return err
		}
		// The DTS extractors need parameter sets even when supplied only in SDP.
		if m.hevc {
			au = append([][]byte{m.vps, m.sps, m.pps}, au...)
		} else {
			au = append([][]byte{m.sps, m.pps}, au...)
		}
	}
	var dts int64
	var err error
	if m.hevc {
		dts, err = m.h265DTS.Extract(au, pts)
	} else {
		dts, err = m.h264DTS.Extract(au, pts)
	}
	if err != nil {
		return ErrMedia
	}
	if !m.started {
		m.origin = dts
		m.started = true
	}
	if m.pending != nil {
		duration := dts - m.previous
		if duration <= 0 || duration > 900000 {
			return fmt.Errorf("unsupported or discontinuous video timestamps; try a different stream")
		}
		m.pending.Duration = uint32(duration)
		part := fmp4.Part{SequenceNumber: m.sequence, Tracks: []*fmp4.PartTrack{{ID: 1, BaseTime: uint64(m.previous - m.origin), Samples: []*fmp4.Sample{m.pending}}}}
		var b seekablebuffer.Buffer
		if err = part.Marshal(&b); err != nil {
			return ErrMedia
		}
		if b.Len() > MaxFrame+65536 {
			return ErrMedia
		}
		if err = m.sink.Write(Packet{Kind: 1, Data: b.Bytes()}); err != nil {
			return err
		}
		m.sequence++
	}
	if pts-dts > 900000 || pts-dts < -900000 {
		return ErrMedia
	}
	payload, err := h264.AVCC(au).Marshal()
	if err != nil {
		return ErrMedia
	}
	m.pending = &fmp4.Sample{PTSOffset: int32(pts - dts), IsNonSyncSample: !key, Payload: payload}
	m.previous = dts
	return nil
}

func (m *videoMux) init() error {
	var codec codecs.Codec
	info := Info{Transport: "RTSP / RTP over TCP", Codec: "H.264"}
	if m.hevc {
		var s h265.SPS
		if s.Unmarshal(m.sps) != nil {
			return ErrMedia
		}
		info.Width, info.Height, info.Codec = s.Width(), s.Height(), "H.265"
		codec = &codecs.H265{VPS: m.vps, SPS: m.sps, PPS: m.pps}
		m.h265DTS.Initialize()
	} else {
		var s h264.SPS
		if s.Unmarshal(m.sps) != nil || len(m.sps) < 4 {
			return ErrMedia
		}
		info.Width, info.Height = s.Width(), s.Height()
		codec = &codecs.H264{SPS: m.sps, PPS: m.pps}
		m.h264DTS.Initialize()
		info.MIME = fmt.Sprintf(`video/mp4; codecs="avc1.%02X%02X%02X"`, m.sps[1], m.sps[2], m.sps[3])
	}
	if info.Width < 1 || info.Height < 1 || info.Width > MaxWidth || info.Height > MaxHeight {
		return fmt.Errorf("preview resolution exceeds 4096 × 2160; select the sub stream")
	}
	var b seekablebuffer.Buffer
	init := fmp4.Init{Tracks: []*fmp4.InitTrack{{ID: 1, TimeScale: 90000, Codec: codec}}}
	if init.Marshal(&b) != nil {
		return ErrMedia
	}
	if m.hevc {
		// Read the hvcC record generated by our muxer, not an arbitrary MP4 input.
		// RFC 6381 uses reversed compatibility bits and trailing-zero-trimmed
		// constraint bytes. Reporting an invented HEVC profile breaks capability checks.
		i := bytes.Index(b.Bytes(), []byte("hvcC"))
		if i < 0 || i+17 > b.Len() {
			return ErrMedia
		}
		cfg := b.Bytes()[i+4:]
		spaces := []string{"", "A", "B", "C"}
		tier := "L"
		if cfg[1]&32 != 0 {
			tier = "H"
		}
		name := fmt.Sprintf("hvc1.%s%d.%X.%s%d", spaces[cfg[1]>>6], cfg[1]&31, bits.Reverse32(binary.BigEndian.Uint32(cfg[2:6])), tier, cfg[12])
		constraints := bytes.TrimRight(cfg[6:12], "\x00")
		for _, v := range constraints {
			name += fmt.Sprintf(".%02X", v)
		}
		info.MIME = `video/mp4; codecs="` + strings.TrimSpace(name) + `"`
	}
	if err := m.sink.Information(info); err != nil {
		return err
	}
	return m.sink.Write(Packet{Kind: 1, Data: b.Bytes()})
}
